x <- c(1, 2, 3, 4, 5)
y <- c(10, 15, 12, 18, 20)
plot(x, y, type="o",main="Line Graph",xlab="X Values",ylab="Y Values")

"""Program Explanation:
The c() function creates numeric vectors. The plot() function creates the graph. The option
type="o" displays points and connecting lines. The main, xlab and ylab arguments add the title
and axis labels."""
